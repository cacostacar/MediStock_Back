    tipo             VARCHAR2(20)   NOT NULL CHECK (tipo IN ('CRITICO', 'ATENCAO', 'INFO')),
    mensagem         VARCHAR2(400)  NOT NULL,
    origem           VARCHAR2(150),
    criado_em        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_alerta_item FOREIGN KEY (item_estoque_id) REFERENCES itens_estoque(id) ON DELETE CASCADE,
    CONSTRAINT fk_alerta_hosp FOREIGN KEY (hospital_id)     REFERENCES hospitais(id)
);

CREATE INDEX ix_itens_hospital  ON itens_estoque (hospital_id);
