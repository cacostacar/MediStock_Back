-- MediStock (Smart HAS) - Camada de persistencia Oracle + PL/SQL
--
-- Conteudo:
--   1. Limpeza dos objetos (script pode ser reexecutado)
--   2. DDL das tabelas (espelha as entidades JPA do back-end + tabela ALERTAS)
--   3. Dados simulados
--   4. Functions  : fn_dias_cobertura_estoque, fn_status_estoque_formatado
--   5. Procedures : prc_registrar_alertas_criticos, prc_relatorio_consumo_hospital
--   6. Exemplos de uso das functions em consultas e das procedures
--
-- Integracao com o back-end (Spring Boot, profile "oracle"):
--   - Ao criar/atualizar um item de estoque, o back-end publica um evento e,
--     apos o commit, chama prc_registrar_alertas_criticos via JDBC.
--   - Endpoints em /api/plsql expoem as procedures e as functions.
-- =============================================================================

SET SERVEROUTPUT ON;


-- =============================================================================
-- 1. LIMPEZA
-- =============================================================================
BEGIN
    FOR obj IN (
        SELECT object_name, object_type
          FROM user_objects
         WHERE object_name IN (
                   'PRC_REGISTRAR_ALERTAS_CRITICOS', 'PRC_RELATORIO_CONSUMO_HOSPITAL',
                   'FN_DIAS_COBERTURA_ESTOQUE', 'FN_STATUS_ESTOQUE_FORMATADO'
               )
    ) LOOP
        EXECUTE IMMEDIATE 'DROP ' || obj.object_type || ' ' || obj.object_name;
    END LOOP;

    FOR tab IN (
        SELECT table_name
          FROM user_tables
         WHERE table_name IN ('ALERTAS', 'ENTREGAS', 'TRANSFERENCIAS', 'HISTORICO_CONSUMO',
                              'ITENS_ESTOQUE', 'USUARIOS', 'HOSPITAIS')
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || tab.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/


