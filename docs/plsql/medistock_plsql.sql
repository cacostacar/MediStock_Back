-- -----------------------------------------------------------------------------
-- PROCEDURE prc_registrar_alertas_criticos
--
-- Proposito:
--   Rotina automatizada que varre os itens de estoque e persiste na tabela
--   ALERTAS as situacoes que exigem acao da equipe:
--     - Estoque CRITICO (<= minimo) ou em ATENCAO (<= minimo * 1.5)
--     - Item VENCIDO                          -> alerta CRITICO
--     - Validade em ate 15 dias               -> alerta ATENCAO
--     - Validade entre 16 e 60 dias           -> alerta INFO
--
-- Funcionamento:
--   1. Abre um CURSOR com os itens do hospital informado (ou de todos).
--   2. Em LOOP, classifica cada item com IF/ELSIF.
--   3. Evita duplicidade: so insere se o mesmo alerta nao foi gerado hoje.
--   4. Cada item roda em um bloco proprio com EXCEPTION, entao a falha de um
--      item e registrada via DBMS_OUTPUT e nao interrompe os demais.
--   5. Faz COMMIT ao final e devolve a quantidade de alertas criados.
--
-- Acionamento pelo back-end (Java):
--   Chamada via JDBC (SimpleJdbcCall) sempre que um item de estoque e criado
--   ou atualizado (evento EstoqueAlteradoEvent) e pelo endpoint
--   POST /api/plsql/alertas/processar.
--
-- Parametros:
--   p_hospital_id   (IN, opcional) - restringe a um hospital; NULL = todos
--   p_total_alertas (OUT)          - quantidade de alertas novos registrados
--
-- Excecoes:
--   OTHERS (geral) - ROLLBACK e ORA-20010
-- -----------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE prc_registrar_alertas_criticos (
    p_hospital_id    IN  itens_estoque.hospital_id%TYPE DEFAULT NULL,
    p_total_alertas  OUT NUMBER
)
IS
    CURSOR c_itens IS
        SELECT ie.id, ie.nome, ie.quantidade_atual, ie.quantidade_minima,
               NVL(ie.unidade_medida, 'un.') AS unidade,
               ie.validade, ie.hospital_id, ie.local_armazenamento
          FROM itens_estoque ie
         WHERE p_hospital_id IS NULL
            OR ie.hospital_id = p_hospital_id;

    v_nivel          VARCHAR2(10);
    v_dias_venc      NUMBER;
    v_ja_registrado  NUMBER;
    v_total_alertas  PLS_INTEGER := 0;
BEGIN
    FOR r_item IN c_itens LOOP
        BEGIN
            -- 1) Alerta de nivel de estoque
            IF r_item.quantidade_atual <= r_item.quantidade_minima THEN
                v_nivel := 'CRITICO';
            ELSIF r_item.quantidade_atual <= r_item.quantidade_minima * 1.5 THEN
                v_nivel := 'ATENCAO';
            ELSE
                v_nivel := NULL;
            END IF;

            IF v_nivel IS NOT NULL THEN
                SELECT COUNT(*)
                  INTO v_ja_registrado
                  FROM alertas
                 WHERE item_estoque_id = r_item.id
                   AND tipo = v_nivel
                   AND mensagem LIKE 'Estoque%'
                   AND TRUNC(criado_em) = TRUNC(SYSDATE);

                IF v_ja_registrado = 0 THEN
                    INSERT INTO alertas (item_estoque_id, hospital_id, tipo, mensagem, origem)
                    VALUES (r_item.id, r_item.hospital_id, v_nivel,
                            'Estoque ' || LOWER(v_nivel) || ': ' || r_item.quantidade_atual || ' ' ||
                            r_item.unidade || ' (minimo ' || r_item.quantidade_minima || ') - ' || r_item.nome,
                            r_item.local_armazenamento);
                    v_total_alertas := v_total_alertas + 1;
                END IF;
            END IF;

            -- 2) Alerta de validade
            IF r_item.validade IS NOT NULL THEN
                v_dias_venc := TRUNC(r_item.validade) - TRUNC(SYSDATE);

                IF v_dias_venc < 0 THEN
                    SELECT COUNT(*)
                      INTO v_ja_registrado
                      FROM alertas
                     WHERE item_estoque_id = r_item.id
                       AND mensagem LIKE 'Item vencido%'
                       AND TRUNC(criado_em) = TRUNC(SYSDATE);

                    IF v_ja_registrado = 0 THEN
                        INSERT INTO alertas (item_estoque_id, hospital_id, tipo, mensagem, origem)
                        VALUES (r_item.id, r_item.hospital_id, 'CRITICO',
                                'Item vencido em ' || TO_CHAR(r_item.validade, 'DD/MM/YYYY') ||
                                ' - ' || r_item.nome,
                                r_item.local_armazenamento);
                        v_total_alertas := v_total_alertas + 1;
                    END IF;

                ELSIF v_dias_venc <= 60 THEN
                    SELECT COUNT(*)
                      INTO v_ja_registrado
                      FROM alertas
                     WHERE item_estoque_id = r_item.id
                       AND mensagem LIKE 'Validade proxima%'
                       AND TRUNC(criado_em) = TRUNC(SYSDATE);

                    IF v_ja_registrado = 0 THEN
                        INSERT INTO alertas (item_estoque_id, hospital_id, tipo, mensagem, origem)
                        VALUES (r_item.id, r_item.hospital_id,
                                CASE WHEN v_dias_venc <= 15 THEN 'ATENCAO' ELSE 'INFO' END,
                                'Validade proxima: vence em ' || v_dias_venc || ' dia(s) - ' || r_item.nome,
                                r_item.local_armazenamento);
                        v_total_alertas := v_total_alertas + 1;
                    END IF;
                END IF;
            END IF;

        EXCEPTION
            -- Falha isolada de um item nao interrompe o processamento dos demais
            WHEN OTHERS THEN
                DBMS_OUTPUT.PUT_LINE('Falha ao processar item ' || r_item.id || ': ' || SQLERRM);
        END;
    END LOOP;

    COMMIT;

    p_total_alertas := v_total_alertas;
    DBMS_OUTPUT.PUT_LINE(v_total_alertas || ' alerta(s) novo(s) registrado(s).');

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20010, 'Erro ao registrar alertas criticos: ' || SQLERRM);
END prc_registrar_alertas_criticos;
/


-- -----------------------------------------------------------------------------
-- PROCEDURE prc_relatorio_consumo_hospital
--
-- Proposito:
--   Gera o relatorio resumido de consumo de um hospital em um mes: totais
--   consolidados (parametros OUT) e o detalhamento por item, com custo,
--   devolvido em um SYS_REFCURSOR para ser percorrido pelo chamador
--   (bloco PL/SQL, SQL Developer ou o back-end Java via JDBC).
--
-- Funcionamento:
--   1. Valida se o hospital existe (senao ORA-20020).
--   2. Calcula a quantidade de itens distintos, o total de unidades e o custo
--      total consumido no mes de referencia.
--   3. Abre o cursor com o detalhamento ordenado do maior para o menor consumo.
--
-- Acionamento pelo back-end (Java):
--   GET /api/plsql/relatorios/consumo/{hospitalId}?mes=AAAA-MM
--
-- Parametros:
--   p_hospital_id     (IN)  - hospital do relatorio
--   p_mes_referencia  (IN)  - qualquer data do mes desejado
--   p_total_itens     (OUT) - itens distintos consumidos no mes
--   p_total_consumido (OUT) - soma das unidades consumidas
--   p_custo_total     (OUT) - soma do custo (quantidade * custo_unitario)
--   p_cursor          (OUT) - detalhamento: item, quantidade, unidade,
--                             custo_unitario, custo_total
--
-- Excecoes:
--   Hospital inexistente -> ORA-20020
--   OTHERS               -> fecha o cursor, se aberto, e ORA-20021
-- -----------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE prc_relatorio_consumo_hospital (
    p_hospital_id      IN  hospitais.id%TYPE,
    p_mes_referencia   IN  DATE,
    p_total_itens      OUT NUMBER,
    p_total_consumido  OUT NUMBER,
    p_custo_total      OUT NUMBER,
    p_cursor           OUT SYS_REFCURSOR
)
IS
    v_existe  NUMBER;
    e_hospital_inexistente EXCEPTION;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM hospitais WHERE id = p_hospital_id;
    IF v_existe = 0 THEN
        RAISE e_hospital_inexistente;
    END IF;

    SELECT COUNT(DISTINCT hc.item_estoque_id),
           NVL(SUM(hc.quantidade_consumida), 0),
           NVL(SUM(ROUND(hc.quantidade_consumida * NVL(ie.custo_unitario, 0), 2)), 0)
      INTO p_total_itens, p_total_consumido, p_custo_total
      FROM historico_consumo hc
      JOIN itens_estoque ie ON ie.id = hc.item_estoque_id
     WHERE hc.hospital_id = p_hospital_id
       AND TRUNC(hc.mes_referencia, 'MM') = TRUNC(p_mes_referencia, 'MM');

    OPEN p_cursor FOR
        SELECT ie.nome                                                       AS item,
               hc.quantidade_consumida                                       AS quantidade,
               NVL(ie.unidade_medida, 'un.')                                 AS unidade,
               ie.custo_unitario                                             AS custo_unitario,
               ROUND(hc.quantidade_consumida * NVL(ie.custo_unitario, 0), 2) AS custo_total
          FROM historico_consumo hc
          JOIN itens_estoque ie ON ie.id = hc.item_estoque_id
         WHERE hc.hospital_id = p_hospital_id
           AND TRUNC(hc.mes_referencia, 'MM') = TRUNC(p_mes_referencia, 'MM')
         ORDER BY hc.quantidade_consumida DESC;

EXCEPTION
    WHEN e_hospital_inexistente THEN
        RAISE_APPLICATION_ERROR(-20020, 'Hospital ' || p_hospital_id || ' nao encontrado.');
    WHEN OTHERS THEN
        IF p_cursor%ISOPEN THEN
            CLOSE p_cursor;
        END IF;
        RAISE_APPLICATION_ERROR(-20021, 'Erro ao gerar relatorio de consumo do hospital ' ||
                                        p_hospital_id || ': ' || SQLERRM);
END prc_relatorio_consumo_hospital;
