CREATE TABLE hospitais (
    id         NUMBER         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR2(150)  NOT NULL,
    endereco   VARCHAR2(200),
    cidade     VARCHAR2(80),
    estado     VARCHAR2(2),
    latitude   NUMBER         NOT NULL,
    longitude  NUMBER         NOT NULL
);

CREATE TABLE usuarios (
    id                   NUMBER         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    primeiro_nome        VARCHAR2(80)   NOT NULL,
    ultimo_nome          VARCHAR2(80)   NOT NULL,
    email_institucional  VARCHAR2(150)  NOT NULL,
    senha_hash           VARCHAR2(255)  NOT NULL,
    criado_em            TIMESTAMP      NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email_institucional)
);

CREATE TABLE itens_estoque (
    id                        NUMBER         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                      VARCHAR2(150)  NOT NULL,
    quantidade_atual          NUMBER(10)     NOT NULL,
    quantidade_minima         NUMBER(10)     NOT NULL,
    unidade_medida            VARCHAR2(20),
    local_armazenamento       VARCHAR2(150),
    hospital_id               NUMBER         NOT NULL,
    validade                  DATE,
    custo_unitario            NUMBER(12,2),
    alto_custo_baixa_demanda  NUMBER(1)      DEFAULT 0 NOT NULL
                              CHECK (alto_custo_baixa_demanda IN (0, 1)),
    atualizado_em             TIMESTAMP      DEFAULT SYSTIMESTAMP,
    CONSTRAINT fk_item_hospital FOREIGN KEY (hospital_id) REFERENCES hospitais(id)
